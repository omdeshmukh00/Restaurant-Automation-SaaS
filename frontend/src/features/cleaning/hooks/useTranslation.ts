export function useTranslation() {
  const [lang, setLang] = useState(cleaningStore.language);

  useEffect(() => {
    const unsubscribe = cleaningStore.subscribe(() => {
      setLang(cleaningStore.language);
    });
    return () => {
      unsubscribe();
    };
  }, []);

  const t = (key: keyof typeof translations['en'] | string): string => {
    const cleanKey = String(key).toLowerCase().replace(/[^a-z0-9]/g, '');
    const dict = (translations[lang as 'en' | 'hi' | 'es'] || translations['en']) as Record<string, string>;
    const foundKey = Object.keys(dict).find(k => k.toLowerCase().replace(/[^a-z0-9]/g, '') === cleanKey);
    if (foundKey) {
      return dict[foundKey];
    }
    const engDict = translations['en'] as Record<string, string>;
    const foundEngKey = Object.keys(engDict).find(k => k.toLowerCase().replace(/[^a-z0-9]/g, '') === cleanKey);
    if (foundEngKey) {
      return engDict[foundEngKey];
    }
    return String(key);
  };

  return { t, lang };
}
